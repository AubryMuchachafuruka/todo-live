/// Look up a definition by id.
AchievementDefinition? achievementById(String id, [List<AchievementDefinition>? definitions]) {
  final list = definitions ?? allAchievementDefinitions();
  try {
    return list.firstWhere((d) => d.id == id);
  } catch (_) {
    return null;
  }
}
