/// Achievement definitions, tiers and categories for STREET LEAGUE.
///
/// Every achievement has Bronze / Silver / Gold / Legendary tier where
/// appropriate, an XP reward, an illustrated badge, and human-readable
/// requirement steps shown in the locked-state UI.

enum AchievementTier {
  bronze,
  silver,
  gold,
  legendary,
}

enum AchievementCategory {
  match,
  league,
  championsLeague,
  dustCup,
  superCup,
  worldCup,
  streetLegend,
  career,
  challenge,
}

/// One unlocked achievement event, produced by the engine.
class AchievementUnlocked {
  final AchievementDefinition definition;
  final DateTime unlockedAt;
  /// Match in which it was unlocked, null for non-match sources.
  final String? matchId;
  final int xpAwarded;

  AchievementUnlocked({
    required this.definition,
    required this.unlockedAt,
    this.matchId,
    this.xpAwarded = 0,
  });
}

/// Definition of an achievement or milestone. Pure data — the engine decides
/// when conditions are satisfied.
class AchievementDefinition {
  /// Stable id used for persistence and duplicate prevention.
  final String id;
  final String name;
  final String description;
  final AchievementTier tier;
  final AchievementCategory category;
  /// XP granted when unlocked.
  final int xpReward;
  /// Progress required to unlock (1 for single-match feats).
  final int target;
  /// Illustrated badge asset.
  final String badgeAsset;
  /// Silhouette shown while locked in the trophy room.
  final String? lockedSilhouetteAsset;
  /// Human-readable requirement steps for the locked UI.
  final List<String> requirementSteps;
  /// Hidden until first unlocked (secret achievements).
  final bool hiddenUntilUnlocked;
  /// True if this is a competition milestone rather than a feat.
  final bool isMilestone;

  const AchievementDefinition({
    required this.id,
    required this.name,
    required this.description,
    required this.tier,
    required this.category,
    this.xpReward = 0,
    this.target = 1,
    required this.badgeAsset,
    this.lockedSilhouetteAsset,
    this.requirementSteps = const [],
    this.hiddenUntilUnlocked = false,
    this.isMilestone = false,
  });
}

